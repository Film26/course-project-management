"""Lab 7 Part C — regenerate the metric source tables from GitHub (read-only).

Usage (repo root, gh CLI logged in):  python docs/labs/lab07/metrics_snapshot.py > docs/labs/lab07/metrics-sources.md
Window: WINDOW_START (inclusive) to the snapshot time printed in the output, all times UTC.
"""
import json
import subprocess
from collections import Counter
from datetime import datetime, timezone

WINDOW_START = '2026-11-20T00:00:00Z'
REPO = 'Film26/course-project-management'


def gh(*args):
    return json.loads(subprocess.check_output(['gh', *args, '-R', REPO], text=True, encoding='utf-8'))


now = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%MZ')
print(f'# Lab 7 Part C — metric sources (generated)\n\nWindow **{WINDOW_START[:10]} 00:00 UTC → {now}** (snapshot). '
      f'Repository `{REPO}` only. Generated by `docs/labs/lab07/metrics_snapshot.py` (read-only `gh` queries).\n')

# M1 completed issues
issues = gh('issue', 'list', '--state', 'all', '--limit', '200', '--json', 'number,title,state,stateReason,createdAt,closedAt,labels')
closed = sorted([i for i in issues if i['closedAt'] and i['closedAt'] >= WINDOW_START], key=lambda i: i['number'])
print('## M1 — Issues closed in the window\n\n| Issue | Closed (UTC) | Reason | Title |\n|---|---|---|---|')
for i in closed:
    print(f"| #{i['number']} | {i['closedAt'][:16].replace('T', ' ')} | {i['stateReason']} | {i['title'][:70]} |")
done = [i for i in closed if i['stateReason'] == 'COMPLETED']
print(f'\n**Value:** {len(done)} completed, {len(closed) - len(done)} not planned/duplicate.\n')
open_i = sorted([i for i in issues if i['state'] == 'OPEN'], key=lambda i: i['number'])
print('Open at the snapshot (context for the interpretation):\n\n| Issue | Opened | Labels | Title |\n|---|---|---|---|')
for i in open_i:
    print(f"| #{i['number']} | {i['createdAt'][:10]} | {', '.join(l['name'] for l in i['labels'])} | {i['title'][:70]} |")

# M2 merged PRs
prs = gh('pr', 'list', '--state', 'merged', '--limit', '200', '--json', 'number,title,mergedAt,baseRefName,reviews')
prs = sorted([p for p in prs if p['mergedAt'] >= WINDOW_START], key=lambda p: p['mergedAt'])
print('\n## M2 — Pull requests merged in the window\n\n| PR | Merged (UTC) | Target | Reviews before merge | Title |\n|---|---|---|---|---|')
nrev = 0
for p in prs:
    revs = [r for r in p['reviews'] if r['submittedAt'] <= p['mergedAt'] and r['state'] in ('APPROVED', 'CHANGES_REQUESTED', 'COMMENTED')]
    nrev += bool(revs)
    txt = ', '.join(sorted({f"{r['author']['login']} {r['state'].lower().replace('_', ' ')}" for r in revs})) or '**none**'
    print(f"| #{p['number']} | {p['mergedAt'][:16].replace('T', ' ')} | `{p['baseRefName']}` | {txt} | {p['title'][:60]} |")
by = Counter(p['baseRefName'] for p in prs)
print(f"\n**Value:** {len(prs)} merged ({', '.join(f'{k} {v}' for k, v in sorted(by.items()))}); "
      f"with at least one review before merge: {nrev}/{len(prs)} = {100 * nrev / max(len(prs), 1):.0f} %.\n")

# M5 CI runs
runs = gh('run', 'list', '--limit', '300', '--created', f'>={WINDOW_START[:10]}', '--json', 'databaseId,workflowName,headBranch,headSha,event,conclusion,status,createdAt')
runs = sorted(runs, key=lambda r: r['createdAt'])
print('## M5 — GitHub Actions runs in the window (all workflows, all branches)\n\n| Run ID | Created (UTC) | Workflow | Event | Branch | Commit | Outcome |\n|---|---|---|---|---|---|---|')
for r in runs:
    print(f"| {r['databaseId']} | {r['createdAt'][:16].replace('T', ' ')} | {r['workflowName']} | {r['event']} | `{r['headBranch']}` | `{r['headSha'][:7]}` | {r['conclusion'] or r['status']} |")
c = Counter((r['workflowName'], r['conclusion'] or r['status']) for r in runs)
print('\n**Value:** ' + '; '.join(f'{w}: {o} {n}' for (w, o), n in sorted(c.items())) + '.')
